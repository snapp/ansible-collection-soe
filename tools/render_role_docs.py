#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Render and verify the role variable tables from meta/argument_specs.yml.

The argument spec is the single source of truth for a role's variables. This
script renders the "Role variables" section of every role README from it (the
text between the BEGIN/END markers) and, in --check mode, fails when:

* a role has no meta/argument_specs.yml, no meta/main.yml or no README.md;
* the README lacks the markers or its rendered section is out of date;
* a non-internal key in defaults/ is missing from the spec, a spec default does
  not equal the defaults/ value, or a spec option carries a default that is not
  defined in defaults/ (the runtime default always comes from defaults/);
* an internal variable (leading underscore) is specified;
* a description says "Defaults to ..." (the default is already shown);
* short_description ends with a period, or a required option has a default;
* meta/main.yml galaxy_info.description differs from the main entry point's
  short_description;
* a README contains a relative Markdown link or an invalid GitHub alert type.

Usage:
    python3 tools/render_role_docs.py [--check] [--roles-dir roles] [ROLE ...]

Requires PyYAML (shipped with ansible-core).
"""
from __future__ import annotations

import argparse
import difflib
import glob
import json
import os
import re
import sys

import yaml

BEGIN = "<!-- BEGIN ROLE VARIABLES -->"
END = "<!-- END ROLE VARIABLES -->"
NOTICE = "<!-- Generated by tools/render_role_docs.py from meta/argument_specs.yml. Do not edit by hand. -->"
REPO_URL = "https://github.com/snapp/ansible-collection-soe/blob/main"
MAX_INLINE_DEFAULT = 60
ALERT_TYPES = {"NOTE", "TIP", "IMPORTANT", "WARNING", "CAUTION"}
RELATIVE_LINK = re.compile(r"\]\((?!https?://|mailto:|#)[^)]+\)")
ALERT = re.compile(r"^> \[!([A-Z]+)\]", re.M)
DEFAULTS_TO = re.compile(r"\b[Dd]efaults? to\b")


def load_yaml(path):
    with open(path, encoding="utf-8") as handle:
        return yaml.safe_load(handle)


def load_defaults(role_dir):
    """Return {key: (value, relative_path)} for every key in defaults/."""
    result = {}
    paths = sorted(glob.glob(os.path.join(role_dir, "defaults", "main.yml"))
                   + glob.glob(os.path.join(role_dir, "defaults", "main", "*.yml")))
    for path in paths:
        data = load_yaml(path) or {}
        rel = os.path.relpath(path, role_dir)
        for key, value in data.items():
            result[key] = (value, rel)
    return result


def is_internal(name):
    return name.startswith("_")


def escape(text):
    return str(text).replace("|", "\\|").replace("\n", " ").strip()


def escape_prose(text):
    """Escape a description cell: pipes, newlines and angle brackets (HTML)."""
    return escape(text).replace("<", "&lt;").replace(">", "&gt;")


def fmt_type(option):
    kind = option.get("type", "str")
    if kind == "list":
        return "list of %s" % option.get("elements", "raw")
    return kind


def fmt_default(role, name, option, defaults):
    if "default" not in option:
        return ""
    value = option["default"]
    if value is None:
        return "`null`"
    if isinstance(value, bool):
        return "`true`" if value else "`false`"
    if isinstance(value, (dict, list)):
        dumped = json.dumps(value)
        if len(dumped) <= MAX_INLINE_DEFAULT:
            return "`%s`" % escape(dumped)
        if name in defaults:
            rel = defaults[name][1]
            return "see [`%s`](%s/roles/%s/%s)" % (rel, REPO_URL, role, rel)
        return "see role defaults"
    if isinstance(value, str):
        return "`''`" if value == "" else "`%s`" % escape(value)
    return "`%s`" % escape(value)


def fmt_description(option):
    desc = option.get("description", "")
    if isinstance(desc, list):
        desc = " ".join(str(part).strip() for part in desc)
    desc = escape_prose(desc)
    if option.get("choices"):
        desc += " Choices: %s." % ", ".join("`%s`" % escape(choice) for choice in option["choices"])
    if option.get("no_log"):
        desc = "**Secret.** " + re.sub(r"^Secret\.\s*", "", desc)
    return desc


def is_common(option):
    return bool(option.get("required")) or "default" not in option or bool(option.get("no_log"))


def option_rows(role, name, option, defaults, depth=0):
    """Yield (name, option, depth) for an option and its nested options."""
    yield name, option, depth
    suffix = "[]." if option.get("type") == "list" else "."
    for child_name, child in (option.get("options") or {}).items():
        yield from option_rows(role, name + suffix + child_name, child, defaults, depth + 1)


def render_table(role, entries, defaults, with_required):
    if not entries:
        return ["_None._", ""]
    if with_required:
        lines = ["| Variable | Type | Required | Default | Description |", "|---|---|---|---|---|"]
    else:
        lines = ["| Variable | Type | Default | Description |", "|---|---|---|---|"]
    for name, option, depth in entries:
        cells = ["`%s`" % name, fmt_type(option)]
        if with_required:
            cells.append("yes" if option.get("required") else "no")
        cells.append(fmt_default(role, name.split(".")[0], option, defaults) if depth == 0 else fmt_default(role, "", option, {}))
        cells.append(fmt_description(option))
        lines.append("| " + " | ".join(cells) + " |")
    lines.append("")
    return lines


def render_section(role, spec, defaults):
    lines = [BEGIN, NOTICE, ""]
    entry_points = spec.get("argument_specs") or {}
    for ep_name, entry in entry_points.items():
        if len(entry_points) > 1:
            lines += ["#### Entry point `%s`: %s" % (ep_name, escape(entry.get("short_description", ""))), ""]
        common, advanced = [], []
        for name, option in (entry.get("options") or {}).items():
            rows = list(option_rows(role, name, option, defaults))
            (common if is_common(option) else advanced).extend(rows)
        lines += ["#### Commonly set", ""]
        lines += render_table(role, common, defaults, with_required=True)
        lines += ["#### Advanced", ""]
        lines += render_table(role, advanced, defaults, with_required=False)
    lines.append(END)
    return "\n".join(lines)


def replace_section(readme, section):
    start = readme.find(BEGIN)
    end = readme.find(END)
    if start == -1 or end == -1 or end < start:
        return None
    return readme[:start] + section + readme[end + len(END):]


def check_spec(role, role_dir, spec, defaults):
    errors = []
    entry_points = spec.get("argument_specs") or {}
    if "main" not in entry_points:
        errors.append("spec has no 'main' entry point")
    specified = set()
    for ep_name, entry in entry_points.items():
        short = entry.get("short_description")
        if not short:
            errors.append("%s: missing short_description" % ep_name)
        elif short.rstrip().endswith("."):
            errors.append("%s: short_description must not end with a period" % ep_name)
        if not entry.get("description"):
            errors.append("%s: missing description" % ep_name)
        for name, option in (entry.get("options") or {}).items():
            specified.add(name)
            if is_internal(name):
                errors.append("%s: internal variable %s must not be specified" % (ep_name, name))
            if option.get("required") and "default" in option:
                errors.append("%s: %s is required but has a default" % (ep_name, name))
            if "default" in option and name not in defaults:
                errors.append("%s: %s has a spec default but is not defined in defaults/" % (ep_name, name))
            if "default" in option and name in defaults and defaults[name][0] != option["default"]:
                errors.append("%s: %s default drift: spec=%r defaults/=%r" % (ep_name, name, option["default"], defaults[name][0]))
            if "default" not in option and name in defaults:
                errors.append("%s: %s is defined in defaults/ (%s) but the spec has no default" % (ep_name, name, defaults[name][1]))
            for row_name, row, _depth in option_rows(role, name, option, defaults):
                desc = row.get("description", "")
                desc_text = " ".join(desc) if isinstance(desc, list) else str(desc)
                if not desc_text.strip():
                    errors.append("%s: %s has no description" % (ep_name, row_name))
                if DEFAULTS_TO.search(desc_text):
                    errors.append("%s: %s description repeats the default ('Defaults to')" % (ep_name, row_name))
                if row.get("type") == "list" and "elements" not in row:
                    errors.append("%s: %s is a list without elements" % (ep_name, row_name))
    for key in defaults:
        if not is_internal(key) and key not in specified:
            errors.append("defaults/ key %s (%s) is not specified" % (key, defaults[key][1]))
    meta_path = os.path.join(role_dir, "meta", "main.yml")
    if not os.path.exists(meta_path):
        errors.append("meta/main.yml is missing")
    else:
        meta = load_yaml(meta_path) or {}
        meta_desc = (meta.get("galaxy_info") or {}).get("description")
        main_short = (entry_points.get("main") or {}).get("short_description")
        if meta_desc != main_short:
            errors.append("meta/main.yml description %r != spec short_description %r" % (meta_desc, main_short))
    return errors


def check_readme(readme):
    errors = []
    for match in RELATIVE_LINK.finditer(readme):
        errors.append("relative link %s (use a full URL)" % match.group(0))
    for match in ALERT.finditer(readme):
        if match.group(1) not in ALERT_TYPES:
            errors.append("invalid GitHub alert type [!%s]" % match.group(1))
    return errors


def process_role(role_dir, check):
    role = os.path.basename(role_dir.rstrip("/"))
    errors = []
    spec_path = os.path.join(role_dir, "meta", "argument_specs.yml")
    readme_path = os.path.join(role_dir, "README.md")
    if not os.path.exists(spec_path):
        return ["meta/argument_specs.yml is missing"]
    if not os.path.exists(readme_path):
        return ["README.md is missing"]
    spec = load_yaml(spec_path) or {}
    defaults = load_defaults(role_dir)
    errors += check_spec(role, role_dir, spec, defaults)
    with open(readme_path, encoding="utf-8") as handle:
        readme = handle.read()
    errors += check_readme(readme)
    rendered = replace_section(readme, render_section(role, spec, defaults))
    if rendered is None:
        errors.append("README.md lacks the %s / %s markers" % (BEGIN, END))
        return errors
    if rendered != readme:
        if check:
            diff = difflib.unified_diff(readme.splitlines(), rendered.splitlines(), "README.md", "README.md (rendered)", lineterm="")
            errors.append("README.md variables section is out of date:\n" + "\n".join(diff))
        else:
            with open(readme_path, "w", encoding="utf-8") as handle:
                handle.write(rendered)
            print("rendered %s" % readme_path)
    return errors


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="verify only; exit 1 on any problem")
    parser.add_argument("--roles-dir", default="roles", help="roles directory (default: roles)")
    parser.add_argument("roles", nargs="*", help="role names (default: every role)")
    args = parser.parse_args()
    roles = args.roles or sorted(os.listdir(args.roles_dir))
    failed = False
    for role in roles:
        role_dir = os.path.join(args.roles_dir, role)
        if not os.path.isdir(role_dir):
            print("%s: not a role directory" % role, file=sys.stderr)
            failed = True
            continue
        for error in process_role(role_dir, args.check):
            print("%s: %s" % (role, error), file=sys.stderr)
            failed = True
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
